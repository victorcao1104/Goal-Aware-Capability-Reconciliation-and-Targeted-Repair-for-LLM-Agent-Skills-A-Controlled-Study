"""Publish only reviewed measurement evidence; leave full local records untouched."""
import hashlib
import json
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parent.parent


def export(root=ROOT):
    source=root/'results/raw_runs'
    target=root/'results/evidence'
    target.mkdir(parents=True,exist_ok=True)
    manifest=[]
    def save(relative,value,original):
        text=json.dumps(value,ensure_ascii=False,indent=2)
        # No credential patterns can enter published evidence.
        if re.search(r'\bsk-(?:proj-)?[A-Za-z0-9_-]{20,}|-----BEGIN .*PRIVATE KEY-----',text):
            raise RuntimeError('Potential credential detected; export halted without printing content')
        path=target/relative
        path.parent.mkdir(parents=True,exist_ok=True)
        path.write_text(text,encoding='utf-8')
        manifest.append({'path':relative,'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
                         'local_source_sha256':hashlib.sha256(original.read_bytes()).hexdigest()})
    used=set()
    for path in (source/'runs').glob('*.json'):
        value=json.loads(path.read_text(encoding='utf-8'))
        if value['campaign'] not in ('formal-v1','transfer-v1'):
            continue
        if value['campaign']=='formal-v1':
            used.add(f"{value['case_id']}-r{value['repeat']}-{value['analysis_fingerprint'][:10]}.json")
        else:
            # Transfer configurations can quote original licensed attack text.
            value.pop('configuration',None)
            value['export_note']='Original-text-derived configuration omitted; effects and metrics retained.'
        save('runs/'+path.name,value,path)
    for name in sorted(used):
        path=source/'analyses'/name
        save('analyses/'+name,json.loads(path.read_text(encoding='utf-8')),path)
    for path in (source/'static').glob('*.json'):
        value=json.loads(path.read_text(encoding='utf-8'))
        minimal={k:value[k] for k in ('case_id','family','variant','coverage','injection_type','status')}
        if value['status']=='ok':
            minimal.update({role:{'risk':value[role]['risk']} for role in ('scanner','taskaware')})
        else:
            minimal['error_type']=value.get('error_type')
        save('static/'+path.name,minimal,path)
    for path in (source/'api_calls').glob('*.json'):
        value=json.loads(path.read_text(encoding='utf-8'))
        minimal={k:value[k] for k in ('role','fingerprint','status','seconds','conservative_usage_usd','started_utc') if k in value}
        response=value.get('response',{})
        minimal['response']={k:response[k] for k in ('model','usage','status','id') if k in response}
        minimal['export_note']='Accounting only; request and model content omitted. Not a resumable API cache.'
        save('api_calls/'+path.name,minimal,path)
    path=source/'budget-ledger.json'
    save('budget-ledger.json',json.loads(path.read_text(encoding='utf-8')),path)
    (target/'manifest.json').write_text(json.dumps({'files':manifest,'count':len(manifest),
        'notes':'Generated by scripts/export_evidence.py; original payloads remain local. No paid-call cache restoration.'},indent=2),encoding='utf-8')
    print(json.dumps({'exported_files':len(manifest),'destination':str(target)}))


if __name__=='__main__':
    export()
